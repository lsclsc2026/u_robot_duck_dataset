#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
DATA_ROOT="${U_ROBOT_DUCK_DATA_ROOT:-${HOME}/data/duck_dataset}"
TOPIC="/camera/front/image/compressed"
SCENE=""
DUCK_PRESENT="unknown"
DUCK_COUNT=""
LIGHTING="unknown"
DISTANCE_RANGE="unknown"
OCCLUSION="unknown"
NOTES=""
SESSION_ID=""
DURATION=""

usage() {
  cat <<'EOF'
Usage:
  record_camera_session.sh --scene NAME [options]

Options:
  --scene NAME                 Required scene identifier/description.
  --duck-present VALUE        true, false, or unknown (default: unknown).
  --duck-count COUNT          Number of visible/placed ducks.
  --lighting TEXT             Lighting condition.
  --distance-range TEXT       Approximate distance range.
  --occlusion TEXT            Occlusion condition.
  --notes TEXT                Free-form notes.
  --session-id ID             Stable ASCII ID; generated by default.
  --duration SECONDS          Stop automatically after this duration.
  --topic TOPIC               CompressedImage topic.
  --root PATH                 Dataset root.
  -h, --help                  Show this help.

Without --duration, press Ctrl-C once to finish and let rosbag close cleanly.
EOF
}

while (($#)); do
  case "$1" in
    --scene) SCENE="${2:?missing value for --scene}"; shift 2 ;;
    --duck-present) DUCK_PRESENT="${2:?missing value for --duck-present}"; shift 2 ;;
    --duck-count) DUCK_COUNT="${2:?missing value for --duck-count}"; shift 2 ;;
    --lighting) LIGHTING="${2:?missing value for --lighting}"; shift 2 ;;
    --distance-range) DISTANCE_RANGE="${2:?missing value for --distance-range}"; shift 2 ;;
    --occlusion) OCCLUSION="${2:?missing value for --occlusion}"; shift 2 ;;
    --notes) NOTES="${2:?missing value for --notes}"; shift 2 ;;
    --session-id) SESSION_ID="${2:?missing value for --session-id}"; shift 2 ;;
    --duration) DURATION="${2:?missing value for --duration}"; shift 2 ;;
    --topic) TOPIC="${2:?missing value for --topic}"; shift 2 ;;
    --root) DATA_ROOT="${2:?missing value for --root}"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

if [[ -z "${SCENE}" ]]; then
  echo "--scene is required" >&2
  usage >&2
  exit 2
fi
if [[ -n "${DURATION}" && ! "${DURATION}" =~ ^[0-9]+([.][0-9]+)?$ ]]; then
  echo "--duration must be a positive number" >&2
  exit 2
fi

if [[ ! -f /opt/ros/humble/setup.bash ]]; then
  echo "ROS 2 Humble was not found; run this script inside unitree-dev" >&2
  exit 1
fi
set +u
source /opt/ros/humble/setup.bash
set -u
unset CYCLONEDDS_URI

detected_type="$(timeout 8s ros2 topic type "${TOPIC}" 2>/dev/null || true)"
if [[ "${detected_type}" != "sensor_msgs/msg/CompressedImage" ]]; then
  echo "Camera topic ${TOPIC} is unavailable or has the wrong type." >&2
  echo "Expected sensor_msgs/msg/CompressedImage, got: ${detected_type:-<none>}" >&2
  echo "Start u_robot_camera_bridge before recording." >&2
  exit 1
fi

init_args=(
  init --root "${DATA_ROOT}" --scene "${SCENE}"
  --duck-present "${DUCK_PRESENT}" --lighting "${LIGHTING}"
  --distance-range "${DISTANCE_RANGE}" --occlusion "${OCCLUSION}"
  --notes "${NOTES}" --topic "${TOPIC}"
)
if [[ -n "${DUCK_COUNT}" ]]; then
  init_args+=(--duck-count "${DUCK_COUNT}")
fi
if [[ -n "${SESSION_ID}" ]]; then
  init_args+=(--session-id "${SESSION_ID}")
fi

session_dir="$("${SCRIPT_DIR}/duck_dataset" "${init_args[@]}")"
bag_dir="${session_dir}/raw/camera_bag"
record_log="${session_dir}/logs/record.log"
"${SCRIPT_DIR}/duck_dataset" mark-recording \
  --session "${session_dir}" --bag "${bag_dir}" >/dev/null
record_command=(
  ros2 bag record
  --storage sqlite3
  --max-cache-size 10485760
  --output "${bag_dir}"
  "${TOPIC}"
)

echo "Session: ${session_dir}"
echo "Recording ${TOPIC} to ${bag_dir}"
set +e
if [[ -n "${DURATION}" ]]; then
  # --foreground is required in an interactive terminal. Without it, rosbag's
  # keyboard handler tries to read from a background process group and the
  # recorder is suspended before it can create the database.
  timeout --foreground --signal=INT --kill-after=60s "${DURATION}s" \
    "${record_command[@]}" 2>&1 | tee "${record_log}"
  record_status=${PIPESTATUS[0]}
else
  "${record_command[@]}" 2>&1 | tee "${record_log}"
  record_status=${PIPESTATUS[0]}
fi
set -e

# GNU timeout returns 124 after delivering SIGINT; rosbag normally returns 0
# when stopped manually. If a recorder was interrupted after creating the DB
# but before writing metadata, reindex can reconstruct the missing file.
if [[ ! -f "${bag_dir}/metadata.yaml" ]] && compgen -G "${bag_dir}/*.db3" >/dev/null; then
  echo "ROS bag metadata is missing; attempting ros2 bag reindex..." | tee -a "${record_log}"
  ros2 bag reindex --storage sqlite3 "${bag_dir}" 2>&1 | tee -a "${record_log}" || true
fi

# A completed (or reconstructed) metadata file is the final authority.
if [[ ! -f "${bag_dir}/metadata.yaml" ]]; then
  failure_reason="recording did not produce a ROS bag (recorder status ${record_status})"
  echo "${failure_reason}" | tee -a "${record_log}" >&2
  "${SCRIPT_DIR}/duck_dataset" mark-record-failed \
    --session "${session_dir}" --reason "${failure_reason}" >/dev/null || true
  echo "Failed session retained at: ${session_dir}" >&2
  exit "${record_status:-1}"
fi
if [[ ${record_status} -ne 0 && ${record_status} -ne 124 && ${record_status} -ne 130 ]]; then
  echo "Warning: rosbag returned status ${record_status}, but the bag metadata is readable." \
    | tee -a "${record_log}" >&2
fi

"${SCRIPT_DIR}/duck_dataset" mark-recorded \
  --session "${session_dir}" --bag "${bag_dir}" >/dev/null

echo "Recording complete. Process it with:"
echo "  ${SCRIPT_DIR}/process_session.sh ${session_dir}"
